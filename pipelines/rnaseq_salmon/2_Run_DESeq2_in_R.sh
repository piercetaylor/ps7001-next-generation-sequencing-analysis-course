#!/bin/bash
#===============================================================================
# Salmon RNA-seq Pipeline - Script 2
# DESeq2 Differential Expression and Functional Enrichment Analysis
# Description: Imports Salmon quantifications, runs DESeq2 DE analysis,
#              performs GO/KEGG enrichment, generates publication figures
#===============================================================================

set -e
set -u
set -o pipefail

#===============================================================================
# Configuration
#===============================================================================
PROJECT_DIR="salmon_rnaseq"
SALMON_DIR="${PROJECT_DIR}/results/salmon"
DESEQ_DIR="${PROJECT_DIR}/results/deseq2"
FIGURES_DIR="${PROJECT_DIR}/results/figures"
ENRICHMENT_DIR="${PROJECT_DIR}/results/enrichment"
SCRIPTS_DIR="${PROJECT_DIR}/scripts"
LOG_DIR="${PROJECT_DIR}/logs"
SAMPLE_SHEET="${PROJECT_DIR}/samples.csv"

ENV_NAME="Salmon_Pipeline"

# Analysis parameters - ADJUST THESE!
ORGANISM="Hs"              # Hs=Human, Mm=Mouse, At=Arabidopsis, etc.
CONDITION_COLUMN="condition"
CONTROL_CONDITION="control"
TREATMENT_CONDITION="treated"
PADJ_CUTOFF=0.05
LFC_CUTOFF=1.0

# Create log file
LOGFILE="${LOG_DIR}/pipeline_2_$(date +%Y%m%d_%H%M%S).log"
exec 1> >(tee -a "${LOGFILE}")
exec 2>&1

echo "=========================================="
echo "Salmon RNA-seq Pipeline - Part 2"
echo "DESeq2 Analysis & Enrichment"
echo "Started: $(date)"
echo "=========================================="

#===============================================================================
# Environment Check
#===============================================================================
echo ""
echo "[STEP 0] Checking environment..."

# Load mamba/conda
module load mamba 2>/dev/null || true

# Activate environment
source activate ${ENV_NAME} || conda activate ${ENV_NAME}

# Verify R is available
if ! command -v Rscript &> /dev/null; then
    echo "ERROR: Rscript not found"
    exit 1
fi

echo "   R version: $(R --version | head -1)"
echo "   Environment: ${ENV_NAME}"

#===============================================================================
# STEP 1: Create R Analysis Script
#===============================================================================
echo ""
echo "[STEP 1] Creating R analysis script..."

cat > ${SCRIPTS_DIR}/deseq2_analysis.R << 'RSCRIPT_EOF'
#!/usr/bin/env Rscript
#===============================================================================
# DESeq2 Differential Expression and Functional Enrichment Analysis
# Generated by Salmon RNA-seq Pipeline
#===============================================================================

suppressPackageStartupMessages({
  library(tximport)
  library(DESeq2)
  library(apeglm)
  library(tidyverse)
  library(pheatmap)
  library(ggrepel)
  library(clusterProfiler)
  library(enrichplot)
  library(ComplexHeatmap)
})

# Get command line arguments from environment
args <- commandArgs(trailingOnly = TRUE)
if (length(args) == 0) {
  # Use environment variables if no args
  project_dir <- Sys.getenv("PROJECT_DIR", "salmon_rnaseq")
  organism <- Sys.getenv("ORGANISM", "Hs")
  control <- Sys.getenv("CONTROL_CONDITION", "control")
  treatment <- Sys.getenv("TREATMENT_CONDITION", "treated")
  padj_cutoff <- as.numeric(Sys.getenv("PADJ_CUTOFF", "0.05"))
  lfc_cutoff <- as.numeric(Sys.getenv("LFC_CUTOFF", "1.0"))
} else {
  project_dir <- args[1]
  organism <- args[2]
  control <- args[3]
  treatment <- args[4]
  padj_cutoff <- as.numeric(args[5])
  lfc_cutoff <- as.numeric(args[6])
}

cat("\n========================================\n")
cat("DESeq2 RNA-seq Analysis\n")
cat("========================================\n")
cat("Project:", project_dir, "\n")
cat("Organism:", organism, "\n")
cat("Comparison:", treatment, "vs", control, "\n")
cat("Cutoffs: padj <", padj_cutoff, ", |log2FC| >", lfc_cutoff, "\n")
cat("========================================\n\n")

# Set paths
salmon_dir <- file.path(project_dir, "results/salmon")
deseq_dir <- file.path(project_dir, "results/deseq2")
figures_dir <- file.path(project_dir, "results/figures")
enrichment_dir <- file.path(project_dir, "results/enrichment")
sample_sheet <- file.path(project_dir, "samples.csv")

# Create output directories
dir.create(deseq_dir, showWarnings = FALSE, recursive = TRUE)
dir.create(figures_dir, showWarnings = FALSE, recursive = TRUE)
dir.create(enrichment_dir, showWarnings = FALSE, recursive = TRUE)

#===============================================================================
# STEP 1: Load Sample Metadata
#===============================================================================
cat("[1/8] Loading sample metadata...\n")

samples <- read.csv(sample_sheet, stringsAsFactors = FALSE)
cat("  Total samples:", nrow(samples), "\n")
cat("  Conditions:", paste(unique(samples$condition), collapse = ", "), "\n")

# Construct paths to Salmon quant files
samples$files <- file.path(salmon_dir, samples$sample_id, "quant.sf")

# Check all files exist
missing <- samples$files[!file.exists(samples$files)]
if (length(missing) > 0) {
  cat("ERROR: Missing quant.sf files:\n")
  cat(paste(missing, collapse = "\n"), "\n")
  quit(status = 1)
}

# Set sample names for columns
names(samples$files) <- samples$sample_id
cat("   All quantification files found\n")

#===============================================================================
# STEP 2: Import Salmon Quantifications with tximport
#===============================================================================
cat("\n[2/8] Importing Salmon quantifications...\n")

# Import transcript-level abundances and aggregate to genes
# Note: If you have a tx2gene mapping file, provide it here
# For now, we'll work at transcript level
txi <- tximport(samples$files, type = "salmon", txOut = TRUE)

cat("   Imported", nrow(txi$counts), "transcripts\n")
cat("   Samples:", ncol(txi$counts), "\n")

# Save raw counts
write.csv(txi$counts, file.path(deseq_dir, "raw_counts.csv"))
write.csv(txi$abundance, file.path(deseq_dir, "tpm_values.csv"))

#===============================================================================
# STEP 3: Create DESeq2 Dataset
#===============================================================================
cat("\n[3/8] Creating DESeq2 dataset...\n")

# Ensure condition is a factor with control as reference
samples$condition <- factor(samples$condition, levels = c(control, treatment))

# Create DESeq2 dataset from tximport
dds <- DESeqDataSetFromTximport(txi, 
                                 colData = samples, 
                                 design = ~ condition)

# Filter low-count genes (at least 10 reads in at least 3 samples)
keep <- rowSums(counts(dds) >= 10) >= 3
dds <- dds[keep, ]

cat("   Retained", nrow(dds), "transcripts after filtering\n")

#===============================================================================
# STEP 4: Run DESeq2 Analysis
#===============================================================================
cat("\n[4/8] Running DESeq2 differential expression analysis...\n")

dds <- DESeq(dds)

# Extract results
res <- results(dds, contrast = c("condition", treatment, control))

# Shrink log2 fold changes for visualization
resLFC <- lfcShrink(dds, 
                    contrast = c("condition", treatment, control), 
                    type = "normal")

# Summary
cat("\n  Results summary:\n")
summary(res, alpha = padj_cutoff)

# Filter significant genes
sig_genes <- as.data.frame(res) %>%
  filter(padj < padj_cutoff, abs(log2FoldChange) > lfc_cutoff) %>%
  arrange(padj)

cat("\n   Significant genes (padj <", padj_cutoff, ", |log2FC| >", lfc_cutoff, "):", nrow(sig_genes), "\n")
cat("    Upregulated:", sum(sig_genes$log2FoldChange > 0), "\n")
cat("    Downregulated:", sum(sig_genes$log2FoldChange < 0), "\n")

# Save results
write.csv(as.data.frame(res), file.path(deseq_dir, "deseq2_results_all.csv"))
write.csv(as.data.frame(resLFC), file.path(deseq_dir, "deseq2_results_shrunk.csv"))
write.csv(sig_genes, file.path(deseq_dir, "deseq2_significant_genes.csv"))

# Normalized counts
norm_counts <- counts(dds, normalized = TRUE)
write.csv(norm_counts, file.path(deseq_dir, "normalized_counts.csv"))

# rlog-transformed counts for visualization
rld <- rlog(dds, blind = FALSE)
write.csv(assay(rld), file.path(deseq_dir, "rlog_counts.csv"))

#===============================================================================
# STEP 5: Quality Control Plots
#===============================================================================
cat("\n[5/8] Generating quality control plots...\n")

# PCA plot
pdf(file.path(figures_dir, "pca_plot.pdf"), width = 8, height = 6)
plotPCA(rld, intgroup = "condition") +
  theme_bw() +
  ggtitle("PCA of RNA-seq Samples")
dev.off()

# Sample distance heatmap
sampleDists <- dist(t(assay(rld)))
sampleDistMatrix <- as.matrix(sampleDists)
rownames(sampleDistMatrix) <- rld$sample_id
colnames(sampleDistMatrix) <- NULL

pdf(file.path(figures_dir, "sample_distances.pdf"), width = 8, height = 7)
pheatmap(sampleDistMatrix,
         clustering_distance_rows = sampleDists,
         clustering_distance_cols = sampleDists,
         main = "Sample-to-Sample Distances")
dev.off()

# Dispersion plot
pdf(file.path(figures_dir, "dispersion_plot.pdf"), width = 8, height = 6)
plotDispEsts(dds, main = "Dispersion Estimates")
dev.off()

cat("   QC plots saved\n")

#===============================================================================
# STEP 6: Differential Expression Plots
#===============================================================================
cat("\n[6/8] Generating DE plots...\n")

# MA plot
pdf(file.path(figures_dir, "ma_plot.pdf"), width = 10, height = 6)
par(mfrow = c(1, 2))
plotMA(res, alpha = padj_cutoff, main = "MA Plot (Unshrunken)")
plotMA(resLFC, alpha = padj_cutoff, main = "MA Plot (Shrunken LFC)")
dev.off()

# Volcano plot
volcano_data <- as.data.frame(res) %>%
  mutate(significant = ifelse(padj < padj_cutoff & abs(log2FoldChange) > lfc_cutoff, 
                              "Significant", "Not Significant"),
         gene_id = rownames(res))

pdf(file.path(figures_dir, "volcano_plot.pdf"), width = 10, height = 8)
ggplot(volcano_data, aes(x = log2FoldChange, y = -log10(padj), color = significant)) +
  geom_point(alpha = 0.5, size = 1) +
  scale_color_manual(values = c("Not Significant" = "grey", "Significant" = "red")) +
  geom_vline(xintercept = c(-lfc_cutoff, lfc_cutoff), linetype = "dashed") +
  geom_hline(yintercept = -log10(padj_cutoff), linetype = "dashed") +
  theme_bw() +
  labs(title = paste(treatment, "vs", control),
       x = "log2 Fold Change",
       y = "-log10(adjusted p-value)") +
  theme(legend.position = "top")
dev.off()

# Heatmap of top 50 DE genes
top_genes <- head(rownames(sig_genes), 50)
if (length(top_genes) > 0) {
  mat <- assay(rld)[top_genes, ]
  mat <- t(scale(t(mat)))  # Z-score normalization
  
  pdf(file.path(figures_dir, "heatmap_top50_genes.pdf"), width = 10, height = 14)
  pheatmap(mat,
           annotation_col = as.data.frame(colData(dds)[, "condition", drop = FALSE]),
           cluster_cols = TRUE,
           cluster_rows = TRUE,
           show_rownames = TRUE,
           fontsize_row = 6,
           main = "Top 50 Differentially Expressed Genes")
  dev.off()
}

cat("   DE plots saved\n")

#===============================================================================
# STEP 7: Functional Enrichment Analysis
#===============================================================================
cat("\n[7/8] Performing functional enrichment analysis...\n")

# Load organism database
org_db <- paste0("org.", organism, ".eg.db")

if (!requireNamespace(org_db, quietly = TRUE)) {
  cat("   WARNING:", org_db, "not installed\n")
  cat("  To install, run in R:\n")
  cat("    BiocManager::install('", org_db, "')\n", sep = "")
  cat("  Skipping enrichment analysis...\n")
} else {
  library(org_db, character.only = TRUE)
  
  # Get significant gene IDs (upregulated and downregulated separately)
  sig_up <- rownames(sig_genes[sig_genes$log2FoldChange > 0, ])
  sig_down <- rownames(sig_genes[sig_genes$log2FoldChange < 0, ])
  sig_all <- rownames(sig_genes)
  
  cat("  Upregulated:", length(sig_up), "\n")
  cat("  Downregulated:", length(sig_down), "\n")
  
  # GO Enrichment - Biological Process (all DE genes)
  if (length(sig_all) > 0) {
    ego_bp <- enrichGO(gene = sig_all,
                       OrgDb = org_db,
                       keyType = "ENSEMBL",  # Adjust if needed
                       ont = "BP",
                       pAdjustMethod = "BH",
                       pvalueCutoff = 0.05,
                       qvalueCutoff = 0.05)
    
    if (!is.null(ego_bp) && nrow(ego_bp) > 0) {
      write.csv(as.data.frame(ego_bp), file.path(enrichment_dir, "GO_BP_enrichment.csv"))
      
      pdf(file.path(figures_dir, "GO_BP_dotplot.pdf"), width = 10, height = 8)
      print(dotplot(ego_bp, showCategory = 20, title = "GO Biological Process"))
      dev.off()
      
      pdf(file.path(figures_dir, "GO_BP_barplot.pdf"), width = 10, height = 8)
      print(barplot(ego_bp, showCategory = 20))
      dev.off()
      
      cat("   GO BP enrichment:", nrow(ego_bp), "terms\n")
    }
  }
  
  # KEGG Pathway Enrichment
  if (length(sig_all) > 0) {
    # Convert to Entrez IDs for KEGG
    gene_entrez <- mapIds(get(org_db), keys = sig_all, 
                         column = "ENTREZID", keytype = "ENSEMBL",
                         multiVals = "first")
    gene_entrez <- na.omit(gene_entrez)
    
    if (length(gene_entrez) > 0) {
      organism_kegg <- switch(organism,
                             "Hs" = "hsa",
                             "Mm" = "mmu",
                             "At" = "ath",
                             "hsa")
      
      kegg <- enrichKEGG(gene = gene_entrez,
                         organism = organism_kegg,
                         pvalueCutoff = 0.05)
      
      if (!is.null(kegg) && nrow(kegg) > 0) {
        write.csv(as.data.frame(kegg), file.path(enrichment_dir, "KEGG_enrichment.csv"))
        
        pdf(file.path(figures_dir, "KEGG_dotplot.pdf"), width = 10, height = 8)
        print(dotplot(kegg, showCategory = 20, title = "KEGG Pathways"))
        dev.off()
        
        cat("   KEGG enrichment:", nrow(kegg), "pathways\n")
      }
    }
  }
  
  cat("   Enrichment analysis complete\n")
}

#===============================================================================
# STEP 8: Generate Summary Report
#===============================================================================
cat("\n[8/8] Generating summary report...\n")

summary_file <- file.path(deseq_dir, "analysis_summary.txt")
sink(summary_file)

cat("========================================\n")
cat("RNA-seq Analysis Summary\n")
cat("========================================\n")
cat("Date:", format(Sys.time(), "%Y-%m-%d %H:%M:%S"), "\n")
cat("Project:", project_dir, "\n")
cat("Comparison:", treatment, "vs", control, "\n")
cat("\n")

cat("Sample Information:\n")
cat("  Total samples:", nrow(samples), "\n")
cat("  Control samples:", sum(samples$condition == control), "\n")
cat("  Treatment samples:", sum(samples$condition == treatment), "\n")
cat("\n")

cat("Data Processing:\n")
cat("  Total transcripts imported:", nrow(txi$counts), "\n")
cat("  Transcripts after filtering:", nrow(dds), "\n")
cat("\n")

cat("Differential Expression:\n")
cat("  Significance cutoffs: padj <", padj_cutoff, ", |log2FC| >", lfc_cutoff, "\n")
cat("  Total significant genes:", nrow(sig_genes), "\n")
cat("  Upregulated:", sum(sig_genes$log2FoldChange > 0), "\n")
cat("  Downregulated:", sum(sig_genes$log2FoldChange < 0), "\n")
cat("\n")

if (nrow(sig_genes) > 0) {
  cat("Top 10 Upregulated Genes:\n")
  top_up <- head(sig_genes[sig_genes$log2FoldChange > 0, ], 10)
  print(top_up[, c("log2FoldChange", "padj")])
  cat("\n")
  
  cat("Top 10 Downregulated Genes:\n")
  top_down <- head(sig_genes[sig_genes$log2FoldChange < 0, ], 10)
  print(top_down[, c("log2FoldChange", "padj")])
}

cat("\n")
cat("Output Files:\n")
cat("  Results: ", deseq_dir, "\n")
cat("  Figures: ", figures_dir, "\n")
cat("  Enrichment: ", enrichment_dir, "\n")
cat("========================================\n")

sink()

cat("   Summary saved:", summary_file, "\n")

#===============================================================================
# Complete
#===============================================================================
cat("\n========================================\n")
cat("Analysis Complete!\n")
cat("========================================\n\n")

cat("Key output files:\n")
cat("   DESeq2 results:", file.path(deseq_dir, "deseq2_significant_genes.csv"), "\n")
cat("   Normalized counts:", file.path(deseq_dir, "normalized_counts.csv"), "\n")
cat("   Volcano plot:", file.path(figures_dir, "volcano_plot.pdf"), "\n")
cat("   PCA plot:", file.path(figures_dir, "pca_plot.pdf"), "\n")
cat("   Summary:", summary_file, "\n\n")

RSCRIPT_EOF

chmod +x ${SCRIPTS_DIR}/deseq2_analysis.R

echo "   R script created: ${SCRIPTS_DIR}/deseq2_analysis.R"

#===============================================================================
# STEP 2: Run R Analysis
#===============================================================================
echo ""
echo "[STEP 2] Running R analysis..."

# Export variables for R script
export PROJECT_DIR=${PROJECT_DIR}
export ORGANISM=${ORGANISM}
export CONTROL_CONDITION=${CONTROL_CONDITION}
export TREATMENT_CONDITION=${TREATMENT_CONDITION}
export PADJ_CUTOFF=${PADJ_CUTOFF}
export LFC_CUTOFF=${LFC_CUTOFF}

# Run R script
Rscript ${SCRIPTS_DIR}/deseq2_analysis.R

#===============================================================================
# Summary
#===============================================================================
echo ""
echo "=========================================="
echo "Pipeline Part 2 Complete!"
echo "Finished: $(date)"
echo "=========================================="
echo ""
echo "Output directories:"
echo "  DESeq2 results: ${DESEQ_DIR}/"
echo "  Figures:        ${FIGURES_DIR}/"
echo "  Enrichment:     ${ENRICHMENT_DIR}/"
echo ""
echo "Key files:"
echo "   ${DESEQ_DIR}/deseq2_significant_genes.csv"
echo "   ${FIGURES_DIR}/volcano_plot.pdf"
echo "   ${FIGURES_DIR}/pca_plot.pdf"
echo "   ${ENRICHMENT_DIR}/GO_BP_enrichment.csv"
echo ""
echo "Log saved to: ${LOGFILE}"